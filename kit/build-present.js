#!/usr/bin/env node
/* =========================================================================
   build-present.js  --  generates kit/deck-present.html from kit/deck.html

   WHY THIS EXISTS
   ---------------
   kit/deck.html is two things at once: the file attendees download, and the
   source the slides PDF is printed from. It is also edited by several people
   on any given day. So the presenting artifact is generated FROM it rather
   than built INTO it.

   This script never touches slide content. It copies the <section class="s">
   markup byte for byte, swaps the <title>, appends a screen-only stylesheet,
   and replaces the deck's small nav script with the presenter one. If a slide
   changes in deck.html, re-run this and the presenting copy catches up.

   RUN:  node kit/build-present.js
   OUT:  kit/deck-present.html   (self-contained, opens from file://)
   ========================================================================= */

const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const SRC = path.join(DIR, 'deck.html');
const OUT = path.join(DIR, 'deck-present.html');

let html = fs.readFileSync(SRC, 'utf8');

/* ---------- 1. sanity gates -------------------------------------------- */

const slideCount = (html.match(/<section class="s[^"]*"/g) || []).length;
if (slideCount === 0) {
  console.error('ABORT: found no <section class="s"> in deck.html');
  process.exit(1);
}

const external = (html.match(/(?:src|href)\s*=\s*["'](?!#|data:|mailto:)[^"']+["']/g) || [])
  .filter(a => /^(?:src|href)\s*=\s*["'](?:https?:)?\/\//.test(a));
if (external.length) {
  console.error('ABORT: deck.html has runtime-external references, offline is not safe:');
  external.forEach(a => console.error('   ' + a));
  process.exit(1);
}

const scripts = html.match(/<script[\s\S]*?<\/script>/g) || [];
if (scripts.length !== 1) {
  console.error(`ABORT: expected exactly 1 <script> in deck.html, found ${scripts.length}.`);
  console.error('The generator replaces that script. Two keydown handlers would double-advance.');
  process.exit(1);
}

/* The grain must survive. If someone scopes the print guard wrong and kills
   .s::after outside @media print, the deck loses its texture on screen. */
const printBlocks = html.match(/@media\s+print\s*\{[\s\S]*?\n\}/g) || [];
const grainKills = (html.match(/\.s::after\s*\{[^}]*display\s*:\s*none/g) || []).length;
const grainKillsInPrint = printBlocks.join('\n').match(/\.s::after\s*\{[^}]*display\s*:\s*none/g) || [];
if (grainKills > grainKillsInPrint.length) {
  console.error('ABORT: a rule hides .s::after (the film grain) outside @media print.');
  console.error('That would strip the texture from the full-screen presenting view.');
  process.exit(1);
}

